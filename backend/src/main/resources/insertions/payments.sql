create table payments
(
    id               bigint generated by default as identity
        primary key,
    amount           numeric(38, 2)              not null,
    payment_method   varchar(255)                not null
        constraint payments_payment_method_check
            check ((payment_method)::text = ANY
                   ((ARRAY ['MOCK_GATEWAY'::character varying, 'CREDIT_CARD'::character varying])::text[])),
    status           varchar(255)                not null
        constraint payments_status_check
            check ((status)::text = ANY ((ARRAY ['SUCCESS'::character varying, 'FAILED'::character varying])::text[])),
    transaction_date timestamp(6) with time zone not null,
    order_id         bigint                      not null
        constraint fk81gagumt0r8y3rmudcgpbk42l
            references orders
);

alter table payments
    owner to postgres;

